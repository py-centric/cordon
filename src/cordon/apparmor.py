"""AppArmor 4.0+ Kernel Mandatory Access Control (MAC) Profile Generator.

Implements FR-3.1..FR-3.5 and EC-05..EC-06 for Cordon universal sandboxes.
Strictly complies with the PyCentric Zero Unicode Em-Dash Rule.
"""

from __future__ import annotations

from cordon.models import CordonProfile


def render_apparmor_profile(
    profile: CordonProfile,
    *,
    wrapper_path: str = "/usr/local/bin/agent-shell",
    profile_name: str = "cordon_shell",
) -> str:
    """Renders a complete AppArmor 4.0+ MAC profile for the given CordonProfile."""
    deny_exec_lines: list[str] = []
    for bin_path in profile.blacklisted_binaries:
        if bin_path.startswith("/usr/bin/"):
            short_name = bin_path.removeprefix("/usr/bin/")
            deny_exec_lines.append(f"  deny /{{usr/,}}bin/{short_name} x,")
        else:
            deny_exec_lines.append(f"  deny {bin_path} x,")

    deny_cred_lines: list[str] = []
    for cred_path in profile.protected_credential_paths:
        mapped = cred_path.replace("~/", "@{HOME}/")
        if not mapped.endswith((".pem", ".p12", ".json", ".netrc", ".pypirc", ".npmrc")):
            clean_dir = mapped.rstrip("/")
            deny_cred_lines.append(f"  deny {clean_dir}/ rwlkmx,")
            deny_cred_lines.append(f"  deny {clean_dir}/** rwlkmx,")
        else:
            deny_cred_lines.append(f"  deny {mapped} rwlkmx,")

    exec_denials = "\n".join(deny_exec_lines)
    cred_denials = "\n".join(deny_cred_lines)

    return f"""# Generated by Cordon Universal Sandbox Engine (ADR-L0-SEC-02)
# Workload Profile: {profile.name}
# Install to: /etc/apparmor.d/usr.local.bin.agent-shell
# Load via:   sudo apparmor_parser -r -W /etc/apparmor.d/usr.local.bin.agent-shell
# Strictly complies with the PyCentric Zero Unicode Em-Dash Rule.

abi <abi/4.0>,

include <tunables/global>

profile {profile_name} {wrapper_path} flags=(attach_disconnected,mediate_deleted) {{
  include <abstractions/base>
  include <abstractions/nameservice>
  include <abstractions/python>
  include <abstractions/ssl_certs>

  # FR-3.4 & EC-06: Unprivileged User Namespace & Mount Transition for Bubblewrap
  userns,
  mount,
  remount,
  umount,
  pivot_root,

  capability sys_chroot,
  capability setpcap,
  capability setuid,
  capability setgid,
  capability dac_override,

  # FR-3.4: Explicit Privilege & Capability Containment
  deny capability net_admin,
  deny capability net_raw,
  deny capability sys_admin,
  deny capability sys_module,
  deny capability sys_rawio,
  deny capability sys_ptrace,
  deny capability sys_boot,
  deny capability mac_admin,
  deny capability mac_override,
  deny ptrace,
  deny signal peer=unconfined,

  network inet stream,
  network inet6 stream,
  network inet dgram,
  network inet6 dgram,
  network unix stream,
  network unix dgram,
  network netlink raw,

  / r,
  /** r,
  /{{usr,bin,lib,lib64,sbin}}/** mr,
  /usr/bin/bwrap ix,
  {wrapper_path} rix,
  /{{usr/,}}bin/{{bash,sh,zsh,dash,env}} rix,
  /usr/** rix,
  /opt/** rix,
  @{{HOME}}/.cargo/bin/** rix,
  @{{HOME}}/.local/bin/** rix,

  @{{HOME}}/** rwk,
  /mnt/** rwk,
  /media/** rwk,
  /srv/** rwk,
  /tmp/** rwkl,
  /var/tmp/** rwkl,
  /dev/shm/** rwkl,
  /dev/{{null,zero,full,random,urandom,tty,pts/*,ptmx}} rw,
  /proc/** rw,
  /sys/fs/cgroup/** r,

  # EC-02: Allow execution of project-local build helpers inside $PWD
  @{{HOME}}/**/node_modules/.bin/** rix,
  @{{HOME}}/**/target/** rix,
  @{{HOME}}/**/.venv/bin/** rix,

  # FR-3.1: Blacklisted Executable Enforcement (Kernel-Level deny ... x)
{exec_denials}
  deny /{{usr/,}}sbin/iptables* x,
  deny /{{usr/,}}sbin/nft x,
  deny /{{usr/,}}sbin/ip x,
  deny /{{usr/,}}sbin/apparmor_parser x,

  # FR-3.2: No-Exec Enforcement on Writable Temp/Cache Paths (Defeats BYOB)
  deny /tmp/** x,
  deny /var/tmp/** x,
  deny /dev/shm/** x,
  deny /run/user/** x,

  # FR-3.3: Sensitive Credential Path Protection (deny ... rwlkmx)
{cred_denials}

  # FR-3.5: Self-Tampering Prevention
  deny {wrapper_path} wkl,
  deny /usr/local/bin/agent-sandbox wkl,
  deny /usr/local/bin/cordon wkl,
  deny /etc/apparmor* wkl,
  deny /etc/apparmor.d/** rwlkmx,
  deny /sys/kernel/security/apparmor/** wkl,
}}
"""
