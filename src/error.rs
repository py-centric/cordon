//! Typed domain errors and RFC 7807 Problem Details for Cordon.

use serde::{Deserialize, Serialize};
use thiserror::Error;

/// Typed domain error enumeration for all Cordon sandbox and policy operations.
#[derive(Debug, Error)]
pub enum CordonError {
    /// Profile slug violates naming rules (`^[a-z0-9][a-z0-9_-]{1,62}$`).
    #[error("Invalid profile name '{0}': must match ^[a-z0-9][a-z0-9_-]{{1,62}}$")]
    InvalidProfileName(String),

    /// Requested workload profile does not exist in the built-in catalog.
    #[error("Unknown profile '{name}'. Available profiles: {available}")]
    UnknownProfile {
        /// Requested profile identifier.
        name: String,
        /// Comma-separated list of valid profile identifiers.
        available: String,
    },

    /// Command vector passed to the sandbox compiler was empty.
    #[error("Target command vector cannot be empty")]
    EmptyCommand,

    /// Canonical filesystem path resolution failed.
    #[error("Failed to resolve canonical path for '{path}': {reason}")]
    PathResolutionFailed {
        /// Input path string.
        path: String,
        /// Underlying OS error description.
        reason: String,
    },

    /// Attempted to mount root (`/`) or user home (`$HOME`) read-write inside the sandbox.
    #[error("Refusing to mount root (/) or entire home directory ('{path}') read-write")]
    UnsafeWorkspaceMount {
        /// Disallowed canonical path.
        path: String,
    },

    /// Invalid network namespace or IPv4 configuration.
    #[error("Invalid network configuration: {0}")]
    InvalidNetworkConfig(String),

    /// Invalid request payload or parameter.
    #[error("Validation error: {0}")]
    InvalidInput(String),

    /// Standard I/O failure.
    #[error("I/O error: {0}")]
    Io(#[from] std::io::Error),

    /// JSON serialization or deserialization failure.
    #[error("Serialization error: {0}")]
    Serialization(#[from] serde_json::Error),

    /// MicroVM backend does not support the requested disk mode (for example Firecracker has no
    /// virtio-fs, so `firecracker` + `virtio-fs-live` is rejected).
    #[error("MicroVM backend '{backend}' does not support disk_mode '{disk_mode}'")]
    IncompatibleVmDiskMode {
        /// Backend wire name.
        backend: String,
        /// Disk mode wire name.
        disk_mode: String,
    },

    /// MicroVM kernel or rootfs image path failed the image allowlist / symlink validation.
    #[error("Refusing MicroVM image '{path}': {reason}")]
    UnsafeMicroVmImage {
        /// Offending path as supplied.
        path: String,
        /// Validation failure reason.
        reason: String,
    },

    /// MicroVM option is valid in the schema but unsupported for this backend or profile.
    #[error("Unsupported MicroVM option: {0}")]
    UnsupportedVmOption(String),

    /// MicroVM runtime prerequisite is unavailable (KVM, tap pool, or VMM binary).
    #[error("MicroVM unavailable: {0}")]
    MicroVmUnavailable(String),
}

/// RFC 7807 compliant problem details payload (`application/problem+json`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Rfc7807ProblemDetails {
    /// URI reference identifying the problem type.
    #[serde(rename = "type")]
    pub problem_type: String,
    /// Short, human-readable summary of the problem type.
    pub title: String,
    /// HTTP status code generated by the origin server.
    pub status: u16,
    /// Human-readable explanation specific to this occurrence of the problem.
    pub detail: String,
    /// URI reference identifying the specific occurrence of the problem.
    pub instance: String,
    /// Request correlation identifier (`Trace-ID`).
    pub trace_id: String,
}

impl Rfc7807ProblemDetails {
    /// Builds problem details for HTTP middleware rejections (auth, host validation,
    /// body limits, and rate limits) using a stable, path-free `detail` message.
    pub fn from_status(
        status: u16,
        title: &str,
        detail: &str,
        instance: &str,
        trace_id: &str,
    ) -> Self {
        Self {
            problem_type: format!("https://pycentric.co.za/errors/{status}"),
            title: title.to_owned(),
            status,
            detail: detail.to_owned(),
            instance: instance.to_owned(),
            trace_id: trace_id.to_owned(),
        }
    }
}

impl CordonError {
    /// Returns the stable, path-free `detail` message exposed to HTTP clients.
    ///
    /// Absolute host paths, OS error strings, and profile internals are never serialized
    /// into RFC 7807 payloads (information disclosure hardening); the rich error text is
    /// preserved server-side and emitted through `tracing::warn!` for correlation via the
    /// `trace_id` returned to the client.
    fn stable_client_detail(&self) -> &'static str {
        match self {
            Self::InvalidProfileName(_) => "Profile name violates the naming rules (see trace id)",
            Self::UnknownProfile { .. } => {
                "Requested profile is not in the built-in catalog (see trace id)"
            }
            Self::EmptyCommand => "Target command vector cannot be empty",
            Self::PathResolutionFailed { .. } => "Path validation failed (see trace id)",
            Self::UnsafeWorkspaceMount { .. } => {
                "Refusing to mount root or home directory read-write (see trace id)"
            }
            Self::InvalidNetworkConfig(_) => "Invalid network configuration (see trace id)",
            Self::InvalidInput(_) => "Invalid request payload or parameter (see trace id)",
            Self::Io(_) => "Internal I/O error (see trace id)",
            Self::Serialization(_) => "Request payload serialization failed (see trace id)",
            Self::IncompatibleVmDiskMode { .. } => {
                "MicroVM backend does not support the requested disk mode (see trace id)"
            }
            Self::UnsafeMicroVmImage { .. } => {
                "MicroVM image path failed validation (see trace id)"
            }
            Self::UnsupportedVmOption(_) => {
                "MicroVM option is not supported for this backend or profile (see trace id)"
            }
            Self::MicroVmUnavailable(_) => {
                "MicroVM runtime is unavailable on this host (see trace id)"
            }
        }
    }

    /// Maps a domain error into an HTTP status code and RFC 7807 problem details structure.
    ///
    /// The `detail` field carries only the stable message from [`Self::stable_client_detail`];
    /// the full error (including host paths and OS errors) is logged server-side.
    pub fn to_problem_details(&self, instance: &str, trace_id: &str) -> Rfc7807ProblemDetails {
        let (status, title) = match self {
            Self::InvalidProfileName(_)
            | Self::EmptyCommand
            | Self::InvalidNetworkConfig(_)
            | Self::InvalidInput(_) => (400_u16, "Bad Request"),
            Self::UnknownProfile { .. } => (404_u16, "Profile Not Found"),
            Self::PathResolutionFailed { .. }
            | Self::UnsafeWorkspaceMount { .. }
            | Self::IncompatibleVmDiskMode { .. }
            | Self::UnsafeMicroVmImage { .. }
            | Self::UnsupportedVmOption(_) => (422_u16, "Unprocessable Entity"),
            Self::MicroVmUnavailable(_) => (503_u16, "Service Unavailable"),
            Self::Io(_) | Self::Serialization(_) => (500_u16, "Internal Server Error"),
        };

        tracing::warn!(
            error = %self,
            instance,
            trace_id,
            status,
            "cordon error mapped to RFC 7807 problem details (rich detail kept server-side)"
        );

        Rfc7807ProblemDetails {
            problem_type: format!("https://pycentric.co.za/errors/{status}"),
            title: title.to_owned(),
            status,
            detail: self.stable_client_detail().to_owned(),
            instance: instance.to_owned(),
            trace_id: trace_id.to_owned(),
        }
    }
}
